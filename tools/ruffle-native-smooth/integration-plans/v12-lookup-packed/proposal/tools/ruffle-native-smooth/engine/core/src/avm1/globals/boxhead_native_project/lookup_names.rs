pub(crate) struct FixedNames<'gc> {
    values: [Option<AvmString<'gc>>; FixedName::COUNT],
}

impl<'gc> FixedNames<'gc> {
    pub(crate) fn new() -> Self {
        Self { values: [None; FixedName::COUNT] }
    }

    #[inline]
    pub(crate) fn get(&mut self, name: FixedName, activation: &mut Activation<'_, 'gc>) -> AvmString<'gc> {
        let slot = &mut self.values[name as usize];
        if let Some(value) = *slot { return value; }
        let value = name.intern(activation);
        *slot = Some(value);
        value
    }

    #[cfg(test)]
    pub(crate) fn initialized(&self) -> usize {
        self.values.iter().filter(|value| value.is_some()).count()
    }
}
